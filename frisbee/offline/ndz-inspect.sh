#!/bin/bash
# Read-only audit of a raw image produced by ndz-extract.sh (run as root, on linux).
# Reports where space goes, and which /lib/modules/* trees are orphans
# (no installed kernel package owns them).
#
# usage: sudo ndz-inspect.sh image.raw [image.raw ...]

[ $# -gt 0 ] || { echo "usage: $0 image.raw [image.raw ...]"; exit 1; }
# several images: run ourselves on each one, in turn
if [ $# -gt 1 ]; then
    for f in "$@"; do
        echo; echo "################################################################ $f"
        "$0" "$f"
    done
    exit
fi
raw=$1
[ -f "$raw" ] || { echo "$raw: no such file"; exit 1; }
[ "$(id -u)" = 0 ] || { echo "must be root"; exit 1; }

mnts=()
dev=$(losetup --find --show --read-only --partscan "$raw") || exit 1
cleanup() {
    for m in "${mnts[@]}"; do umount "$m" 2>/dev/null; rmdir "$m" 2>/dev/null; done
    losetup -d "$dev"
}
trap cleanup EXIT

echo "=== layout of $raw"
lsblk -o NAME,SIZE,FSTYPE,LABEL "$dev"

# partitions if any, otherwise the loop device itself holds the filesystem
parts=$(ls ${dev}p* 2>/dev/null)
[ -n "$parts" ] || parts=$dev

for p in $parts; do
    fstype=$(blkid -o value -s TYPE "$p")
    [ -n "$fstype" ] || continue
    case $fstype in swap|vfat) continue;; esac
    m=$(mktemp -d); opts=ro
    [ "$fstype" = ext4 -o "$fstype" = ext3 ] && opts=ro,noload
    mount -o $opts "$p" "$m" 2>/dev/null || { echo "cannot mount $p ($fstype)"; rmdir "$m"; continue; }
    mnts+=("$m")
    [ -d "$m/etc" ] || { echo "--- $p ($fstype): no /etc, skipped"; continue; }

    echo; echo "##################### $p ($fstype)"
    . "$m/etc/os-release" 2>/dev/null; echo "OS: $PRETTY_NAME"
    df -h "$m" | tail -1

    echo; echo "=== top-level usage"
    du -xh --max-depth=1 "$m" 2>/dev/null | sort -rh | head -12
    echo; echo "=== biggest second-level dirs"
    du -xh --max-depth=2 "$m"/usr "$m"/var "$m"/lib "$m"/boot "$m"/opt 2>/dev/null | sort -rh | head -15

    echo; echo "=== /lib/modules trees"
    modroot="$m/usr/lib/modules"; [ -d "$modroot" ] || modroot="$m/lib/modules"
    ls "$m"/boot 2>/dev/null | grep -E '^(vmlinuz|initrd|initramfs)' | sed 's/^/boot: /'
    for d in "$modroot"/*/; do
        [ -d "$d" ] || continue
        v=$(basename "$d"); size=$(du -sh "$d" | cut -f1)
        owner=
        # modules.dep is generated by depmod, so no package owns it: look at the kernel/ dir,
        # under both the legacy and the merged-usr spelling
        for base in /usr/lib/modules /lib/modules; do
            if [ -d "$m/var/lib/dpkg" ]; then
                owner=$(chroot "$m" dpkg -S "$base/$v/kernel" 2>/dev/null | head -1 | cut -d: -f1)
            elif [ -d "$m/var/lib/rpm" ]; then
                owner=$(chroot "$m" rpm -qf "$base/$v/kernel" 2>/dev/null | head -1)
                echo "$owner" | grep -q 'not owned' && owner=
            fi
            [ -n "$owner" ] && break
        done
        [ -n "$owner" ] && [ "$owner" != "-" ] || owner="*** ORPHAN ***"
        printf '%-12s %-35s %s\n' "$size" "$v" "$owner"
    done

    echo; echo "=== installed kernel packages"
    if [ -d "$m/var/lib/dpkg" ]; then
        chroot "$m" dpkg-query -W -f='${Package} ${Installed-Size}KB\n' 'linux-image-*' 'linux-modules-*' 'linux-headers-*' 2>/dev/null | grep -v '^$' | sort
    elif [ -d "$m/var/lib/rpm" ]; then
        chroot "$m" rpm -q kernel-core kernel-modules kernel-devel 2>/dev/null
    fi
    if [ -d "$m/var/lib/snapd/snaps" ]; then
        echo; echo "=== snaps on disk"; ls -lhS "$m"/var/lib/snapd/snaps | grep snap
    fi
    echo; echo "=== ext4 vs reality"
    dumpe2fs -h "$p" 2>/dev/null | grep -E 'Block count|Free blocks|Inode count|Inode size|features|Journal size'

    echo; echo "=== known leftovers"
    for x in var/cache var/lib/apt/lists var/lib/dnf var/log var/log/journal \
             usr/src usr/share/doc usr/share/man usr/share/locale root tmp var/tmp \
             var/lib/snapd var/lib/flatpak; do
        [ -e "$m/$x" ] && du -sh "$m/$x" 2>/dev/null
    done
    echo; echo "=== largest files"
    find "$m" -xdev -type f -size +20M -printf '%s\t%p\n' 2>/dev/null | sort -rn | head -10 \
        | awk -F'\t' '{printf "%6.0f MB  %s\n",$1/1048576,$2}'
done
